import random
import time

def generate_random_data(size):
    """
    Генерує список цілих чисел у діапазоні від -10 000 до 10 000.
    """
    return [random.randint(-10000, 10000) for _ in range(size)]


# ----------------------------------------------------------------------
# Спосіб 1: Повне сортування масиву та взяття 6-го найбільшого елемента
# ----------------------------------------------------------------------
def method_1_sort(arr):
    arr_copy = arr.copy()
    # Сортування за спаданням для отримання 6-го найбільшого за індексом 5
    arr_copy.sort(reverse=True)
    return arr_copy[5]


# ----------------------------------------------------------------------
# Спосіб 2: Масив з 6 найбільших елементів (підтримка у відсортованому вигляді)
# ----------------------------------------------------------------------
def method_2_top6_array(arr):
    # Зберігаємо 6 найбільших елементів у порядку зростання: top6[0] - найменший серед 6 найбільших
    top6 = sorted(arr[:6])

    for val in arr[6:]:
        if val > top6[0]:
            top6[0] = val
            # Підтримуємо відсортованість масиву top6
            top6.sort()

    # 6-й найбільший буде найменшим у top6 (індекс 0)
    return top6[0]


# ----------------------------------------------------------------------
# Спосіб 3: Знаходження максимуму 6 разів (із заміною знайдених на -inf)
# ----------------------------------------------------------------------
def method_3_find_max_6_times(arr):
    arr_copy = arr.copy()
    max_val = None
    for _ in range(6):
        max_val = max(arr_copy)
        max_idx = arr_copy.index(max_val)
        arr_copy[max_idx] = float('-inf')  # Замінюємо на найменше можливе значення
    return max_val


# ----------------------------------------------------------------------
# Функція для вимірювання часу виконання у мілісекундах
# ----------------------------------------------------------------------
def measure_time(method, data):
    start_time = time.perf_counter()
    method(data)
    end_time = time.perf_counter()
    return (end_time - start_time) * 1000  # Переведення в мілісекунди


# ----------------------------------------------------------------------
# Головний блок запуску експериментів та виведення результатів
# ----------------------------------------------------------------------
if __name__ == "__main__":
    # Розміри вхідних даних відповідно до завдання
    sizes = [10_000, 100_000, 1_000_000, 10_000_000]
    # Примітка: 100_000_000 опціонально через обмеження оперативної пам'яті

    print(f"{'Розмір вхідних даних':<22} | {'Спосіб 1 (Сортування)':<23} | {'Спосіб 2 (Масив 6)':<23} | {'Спосіб 3 (6 макс.)':<23}")
    print("-" * 97)

    for size in sizes:
        # 3 запуски для оцінки середнього часу
        t1_runs, t2_runs, t3_runs = [], [], []

        for _ in range(3):
            data = generate_random_data(size)

            t1_runs.append(measure_time(method_1_sort, data))
            t2_runs.append(measure_time(method_2_top6_array, data))
            t3_runs.append(measure_time(method_3_find_max_6_times, data))

        # Форматування запусків у форматі: середнє(t1 t2 t3)
        avg1 = sum(t1_runs) / 3
        avg2 = sum(t2_runs) / 3
        avg3 = sum(t3_runs) / 3

        res1_str = f"{avg1:.1f} ({t1_runs[0]:.1f} {t1_runs[1]:.1f} {t1_runs[2]:.1f})"
        res2_str = f"{avg2:.1f} ({t2_runs[0]:.1f} {t2_runs[1]:.1f} {t2_runs[2]:.1f})"
        res3_str = f"{avg3:.1f} ({t3_runs[0]:.1f} {t3_runs[1]:.1f} {t3_runs[2]:.1f})"

        print(f"{size:<22,}".replace(',', ' ') + f" | {res1_str:<23} | {res2_str:<23} | {res3_str:<23}")